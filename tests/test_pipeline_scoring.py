"""
Regression test: the improved response shown to users must be the text that
gets scored, and bias_reduction must come from those scores.

Runs offline: the LLM scorer and the rewrite call are replaced with fakes.
"""

import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))

from biaslense.src.core import bamip_pipeline
from biaslense.src.core.llm_scorer import LLMScoreResult

BIASED = "Sikhism is an offshoot of Islam and borrows most of its beliefs from it."
REWRITE = "Sikhism is an independent religion founded by Guru Nanak in Punjab."
NOTE = "\n\n*This response has been substantially rewritten.*"


def _score(value: int) -> LLMScoreResult:
    return LLMScoreResult(value, value, value, value, value, "r", "r", "r", "r", "r")


class FakeScorer:
    def __init__(self):
        self.scored = []

    def score(self, text, prompt):
        self.scored.append(text)
        return _score(4 if text == REWRITE else 1)


def _make_pipeline(monkeypatch):
    monkeypatch.setattr(bamip_pipeline, "LLMScorer", FakeScorer)
    pipeline = bamip_pipeline.BAMIPPipeline()
    monkeypatch.setattr(pipeline, "_generate_improved_response", lambda *args: (REWRITE, NOTE))
    return pipeline


def test_shown_rewrite_is_the_scored_text(monkeypatch):
    pipeline = _make_pipeline(monkeypatch)
    result = pipeline.process_prompt("Is Sikhism a branch of Islam?", BIASED)

    assert pipeline.llm_scorer.scored == [BIASED, REWRITE]  # note is not scored
    assert result.improved_response == REWRITE + NOTE
    assert result.mitigation_result.improved_bias_result.overall_score == 4.0


def test_bias_reduction_is_share_of_gap_closed(monkeypatch):
    pipeline = _make_pipeline(monkeypatch)
    result = pipeline.process_prompt("Is Sikhism a branch of Islam?", BIASED)

    # 1.0 -> 4.0 closes 3 of the 4 points between the original and a perfect 5.0
    assert result.mitigation_result.bias_reduction_score == 0.75


def test_strategy_reasoning_has_no_unsourced_claims(monkeypatch):
    pipeline = _make_pipeline(monkeypatch)
    result = pipeline.process_prompt("Is Sikhism a branch of Islam?", BIASED)

    assert "%" not in result.strategy_selection_reasoning
    assert "Generated by" not in result.improved_response
